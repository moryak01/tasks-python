# Err2. Прочитать два целых числа и вывести их частное с одним знаком после точки.
# При делении на ноль вывести «Делить на ноль нельзя». Нечисловой ввод обрабатывать не требуется.
a = int(input('Введите первое число: '))
b = int(input('Введите второе число: '))
try:
    print(f"{a / b:.1f}")
except ZeroDivisionError:
    print("Делить на ноль нельзя")
