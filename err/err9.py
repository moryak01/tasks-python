# Err9. Прочитать возраст. Если число отрицательное или больше 120, поднять ValueError
# «Возраст вне допустимого диапазона» и поймать его же: «Отклонено:» и текст ошибки.
# Корректный возраст вывести как «Принято:» и число.
try:
    age = int(input())
    if age < 0 or age > 120:
        raise ValueError("Возраст вне допустимого диапазона")
    print("Принято:", age)
except ValueError as e:
    print("Отклонено:", e)
