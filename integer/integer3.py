# Дан размер файла в байтах. 
# Используя операцию деления нацело, найти количество полных килобайтов, которые занимает данный файл (1 килобайт = 1024 байта).

bytes_size = int(input('введите размер файла в байтах - '))
kb_size = bytes_size / 1024

print(f'количество полных килобайтов - {kb_size}')