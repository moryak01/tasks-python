# While2. Даны положительные числа A и B (A > B). На отрезке длины A размещено максимально возможное
# количество отрезков длины B. Не используя * и /, найти количество отрезков B на отрезке A.
a = int(input())
b = int(input())
free = a
count = 0
while free >= b:
    free -= b
    count += 1
print(count)
