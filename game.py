# --- Заголовок ------------------------------------
title = "ПОДЗЕМЕЛЬЕ: ТИХИЙ КОЛОДЕЦ"
frame = "=" * 31
print(frame)
print(" " + title + " ")
print(frame)
print()

# --- Знакомство с героем --------------------------
print("Как зовут героя?")
hero_name = input()
print(f"Добро пожаловать, {hero_name}!")
print("Ты входишь в подземелье. Здесь темно и пахнет сыростью.")
print()

# --- Настройка героя -------------------------------
print("Настройка героя.")
print("Здоровье, сила, ловкость, выносливость и удача — по одному числу в строке:")
health = int(input())
strength = int(input())
stamina = int(input())
luck = int(input())

# --- Расчёт урона ----------------------------------
base_attack = 10
damage = base_attack + strength * 1.5
crit_damage = damage * 2

# --- Формуляр героя --------------------------------
print("Характеристики героя:")
print(f"Здоровье: {health}")
print(f"Сила: {strength}")
print(f"Выносливость: {stamina}")
print(f"Удача: {luck}")
print()
print(f"Урон героя: {damage:.1f}")
print(f"Критический урон: {crit_damage:.1f}")

# --- Меню действий ---------------------------------
print("Что делаешь?")
print("1 - осмотреться")
print("2 - идти вперёд")
print("3 - отдохнуть")
print("4 - посмотреть на карту")
print("5 - зажечь факел")
# пункты 4 и 5 — твои, по одной строке print на каждый
print()

# --- Выбор героя -----------------------------------
choice = input()

match choice:
    case "1":
        print("Вы осмотрелись. Комната пуста, только пыль на полу.")
    case "2":
        stamina -= 2
        print("Вы осторожно идёте вперёд. Пол скрипит под ногами.")
    case "3":
        print("Вы решили отдохнуть на камне. Вдалеке слышны чьи-то шаги")
    case "4":
        print("Вы посмотрели на карту. В темноте трудно понять где вы находитесь.")
    case "5":
        strength -= 10
        print("Вы зажгли факел. Вы видите дорогу, но теперь вас легче заметить.")
    case _:
        print('Такого действия нет.')

# --- Прощание ---
print(frame)
print(f'Удачи, {hero_name}!')
print(frame)

print(stamina)