# For13. Дано целое число N (> 0). Найти значение выражения 1.1 - 1.2 + 1.3 - ... (N слагаемых, знаки чередуются).
n = int(input())
total = 0.0
sign = 1                      # знак текущего слагаемого
for i in range(1, n + 1):
    total += sign * (10 + i) / 10
    sign = -sign              # переворачиваем знак на каждой итерации
print(total)
