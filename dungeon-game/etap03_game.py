# --- Заголовок ------------------------------------
title = "ПОДЗЕМЕЛЬЕ: СОЛЯНЫЕ ШАХТЫ"
frame = "=" * 31

print(frame)
print(" " + title + " ")
print(frame)
print()

# --- Знакомство с героем --------------------------
print("Как зовут героя?")
hero_name = input()
print(f"Добро пожаловать, {hero_name}!")
print("Ты входишь в подземелье. Здесь темно и пахнет сыростью.")
print()

# --- Настройка героя -------------------------------
print("Настройка героя.")
print("Здоровье, сила, ловкость, выносливость — по одному числу в строке:")
health = int(input())
strength = int(input())
agility = int(input())
endurance = int(input())
print()

# --- Расчёт урона ----------------------------------
base_attack = 10
damage = base_attack + strength * 1.5
crit_damage = damage * 2
stamina = health // 10 + endurance

# --- Формуляр героя --------------------------------
print("Характеристики героя:")
print(f"Здоровье: {health}")
print(f"Сила: {strength}")
print(f"Ловкость: {agility}")
print(f"Выносливость: {endurance}")
print()
print(f"Урон героя: {damage:.1f}")
print(f"Критический урон: {crit_damage:.1f}")
print(f"Запас сил: {stamina}")
print()

# --- Меню действий ---------------------------------
print("Что делаешь?")
print("1 - осмотреться")
print("2 - идти вперёд")
print("3 - отдохнуть")
print("4 - прислушаться")
print("5 - зажечь факел")
print()

# --- Выбор действия --------------------------------
choice = input()
print()

match choice:
    case "1":
        print("Вы осмотрелись. Каменный круг стен, на дне — лужа и пыль.")

    case "2":
        stamina = stamina - 2   # дорога утомляет
        print("Вы осторожно идёте вперёд. Пол скрипит под ногами.")

    case "3":
        stamina = stamina + 3   # отдых возвращает силы
        print("Вы садитесь на пол и переводите дух. Силы возвращаются.")

    case "4":
        print("Вы замираете и слушаете. Где-то капает вода, и больше ни звука.")

    case "5":
        stamina = stamina - 1   # факел стоит немного сил
        print("Вы зажигаете факел. Тени разбегаются по стенам.")

    case _:
        print("Такого действия нет.")

# --- Состояние героя -------------------------------
print()
print(f"Здоровье: {health} Запас сил: {stamina}")

# --- Прощание --------------------------------------
print()
print(frame)
print(f"Удачи, {hero_name}!")
print(frame)
